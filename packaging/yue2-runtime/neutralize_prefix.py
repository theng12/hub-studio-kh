#!/usr/bin/env python3
"""Remove the build user's home path from a built Python runtime.

Two carriers, both generated by the interpreter's own build:

* `lib/python3.12/_sysconfigdata__darwin_darwin.py` records the prefix it was built at — for the
  uv-provided Python `/Users/<builder>/.local/share/uv/python/...` — 21 times.
* `lib/libpython3.12.dylib` carries that same path as its `LC_ID_DYLIB`.

Both would ship in every DMG. The file must stay (CPython's `sysconfig` imports it) and the library
is the interpreter's own copy of itself; neither is deleted. `sys.prefix` does not come from either:
it is derived from the executable's location, so a runtime moved into the app still reports the
right prefix once the recorded build path is neutralised. Nothing links the dylib by that path (the
shipped `bin/python3.12` is statically linked — checked with `otool -L`), so its id can be rewritten
safely. Every replacement is the fixed, non-personal root below, so the same tree built anywhere has
the same bytes.

    neutralize_prefix.py <runtime-tree>
"""
import re
import subprocess
import sys
from pathlib import Path

NEUTRAL = "/opt/studiohub-yue2-runtime"
GENERATED = "lib/python3.12/_sysconfigdata__darwin_darwin.py"
HOME_PATH = re.compile(r"/Users/[^/\"'\s]+")


def neutralize(tree: Path) -> list[str]:
    path = tree / GENERATED
    if not path.is_file():
        return []
    text = path.read_text()
    found = re.search(r'"prefix":\s*"([^"]+)"', text)
    if not found:
        raise SystemExit(f"{path}: no prefix recorded; refusing to guess what to rewrite")
    prefix = found.group(1)
    changed = sorted(set(HOME_PATH.findall(text)))
    if not changed:
        return []
    # A built tree is chmod a-w, so the write needs the directory restored and taken away again.
    directory_mode = path.parent.stat().st_mode & 0o777
    path.parent.chmod(directory_mode | 0o200)
    path.chmod(0o644)
    text_after = text.replace(prefix, NEUTRAL)
    path.write_text(text_after)
    # The interpreter is asked to recompile it if the mtime allows; a stale .pyc next to a read-only
    # source is the one way this could disagree with itself.
    cached = path.parent / "__pycache__"
    if cached.is_dir():
        for stale in cached.glob(path.stem + "*.pyc"):
            stale.chmod(0o644)
            stale.unlink()
    path.chmod(0o444)
    path.parent.chmod(directory_mode)
    return changed


THIN_MAGIC = {0xFEEDFACE, 0xFEEDFACF}
FAT_MAGIC = {0xCAFEBABE, 0xBEBAFECA}


def _macho_ids(tree: Path):
    """Yield (path, install-name) for Mach-O files whose own id names a home directory."""
    for path in tree.rglob("*"):
        if path.is_symlink() or not path.is_file():
            continue
        try:
            with path.open("rb") as stream:
                head = stream.read(4)
        except OSError:
            continue
        if len(head) < 4:
            continue
        # Thin Mach-O writes its magic little-endian on arm64; a universal binary writes CAFEBABE
        # big-endian. Either endianness reading being a Mach-O magic means it is one.
        if int.from_bytes(head, "little") not in THIN_MAGIC and \
                int.from_bytes(head, "big") not in FAT_MAGIC:
            continue
        out = subprocess.run(["otool", "-D", str(path)], capture_output=True, text=True)
        lines = [line.strip() for line in out.stdout.splitlines() if line.strip()]
        if len(lines) < 2 or not lines[-1].startswith("/Users/"):
            continue
        yield path, lines[-1]


def neutralize_binaries(tree: Path) -> list[str]:
    """Rewrite a Mach-O's own install name to the neutral root and re-sign it ad hoc."""
    changed = []
    for path, install_name in _macho_ids(tree):
        directory_mode = path.parent.stat().st_mode & 0o777
        mode = path.stat().st_mode & 0o777
        path.parent.chmod(directory_mode | 0o200)
        path.chmod(mode | 0o200)
        tail = install_name[install_name.index("/lib/"):] if "/lib/" in install_name \
            else f"/lib/{path.name}"
        target = NEUTRAL + tail
        subprocess.run(["install_name_tool", "-id", target, str(path)], check=True)
        # Changing the load commands invalidates any signature, so sign it again ad hoc — the same
        # thing the stager does for the rest of the app. Ad-hoc signatures carry no timestamp, so
        # two builds of the same tree still produce the same bytes.
        subprocess.run(["codesign", "--force", "--sign", "-", str(path)], check=True,
                       capture_output=True)
        path.chmod(mode)
        path.parent.chmod(directory_mode)
        changed.append(f"{path.relative_to(tree)} -> {target}")
    return changed


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    root = Path(sys.argv[1])
    homes = neutralize(root)
    print(f"neutralised {len(homes)} home path(s): {' '.join(homes) or 'none'}")
    binaries = neutralize_binaries(root)
    print(f"neutralised {len(binaries)} Mach-O install name(s): {'; '.join(binaries) or 'none'}")
